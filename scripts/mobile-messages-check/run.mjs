import { createServer } from 'vite'
import react from '@vitejs/plugin-react'
import tailwindcss from '@tailwindcss/vite'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { mkdirSync } from 'node:fs'
const here=dirname(fileURLToPath(import.meta.url)),root=resolve(here,'../..')
const server=await createServer({configFile:false,root:here,plugins:[react(),tailwindcss()],resolve:{alias:[{find:/^@\/aetheris\/(store|read-receipts|MessageAttachments|deals-ui|meeting-brief-ui|workspaces\/StartWorkspace|avatar)$/,replacement:resolve(here,'mock.tsx')},{find:'@',replacement:resolve(root,'src')}]},server:{host:'127.0.0.1',port:0,fs:{allow:[root]}}})
await server.listen()
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE??resolve(root,'node_modules/playwright/index.mjs'))
const browser=await chromium.launch()
const url='http://127.0.0.1:'+server.httpServer.address().port
const assert=(value,label)=>{if(!value)throw Error(label);console.log('PASS '+label)}
const shots=process.env.MESSAGE_SCREENSHOTS
if(shots)mkdirSync(shots,{recursive:true})
try {
 for(const social of [false,true]) for(const theme of ['dark','light']) for(const width of [320,390,768,1440]) {
  const context=await browser.newContext({viewport:{width,height:844}})
  const page=await context.newPage(),errors=[]
  page.on('pageerror',error=>errors.push(error.message))
  await page.goto(url+'/?social='+social)
  await page.evaluate(theme=>document.documentElement.dataset.theme=theme,theme)
  const inbox=page.getByRole('complementary',{name:'Conversations',exact:true})
  const select=name=>inbox.locator('.msg-thread-tile').filter({hasText:name}).click()
  const back=async()=>{if(width<768)await page.getByRole('button',{name:'Back to conversations'}).click();else await page.getByRole('button',{name:'New message'}).click(),await page.getByRole('button',{name:'Conversations',exact:true}).click()}
  await inbox.waitFor()
  assert((await page.evaluate(()=>window.reads)).length===0,'inbox does not mark an unopened thread read')
  await select('Alex Example')
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'conversation fits '+width)
  await page.getByPlaceholder('Write a message…').fill('Draft for Alex')
  if(shots&&width===390)await page.screenshot({path:resolve(shots,`${social?'social':'business'}-${theme}-chat.png`),fullPage:true})
  await back()
  assert(await inbox.isVisible(),'Back reopens the list')
  assert(await page.evaluate(()=>localStorage.getItem('aetheris-intros-thread'))===null,'Back clears remembered selection')
  await select('Blair Example')
  assert(await page.getByPlaceholder('Write a message…').inputValue()==='','draft does not follow another recipient')
  await back();await select('Alex Example')
  assert(await page.getByPlaceholder('Write a message…').inputValue()==='Draft for Alex','original recipient keeps their draft')
  await page.getByRole('button',{name:'New message'}).click()
  await page.getByRole('textbox',{name:'Search members'}).fill('no match')
  await page.getByRole('status').filter({hasText:'No members match'}).waitFor()
  await page.getByRole('textbox',{name:'Search members'}).fill('HVAC')
  await page.getByRole('button',{name:'Message Casey Example',exact:true}).click()
  await page.getByPlaceholder('Write a message…').fill('Hello Casey')
  await page.evaluate(()=>window.failSend=true)
  await page.getByRole('button',{name:'Send message',exact:true}).click()
  await page.getByRole('alert').filter({hasText:'Example failed send'}).waitFor()
  assert(await page.getByPlaceholder('Write a message…').inputValue()==='Hello Casey','failed send preserves draft')
  await page.evaluate(()=>window.failSend=false)
  await page.getByRole('button',{name:'Retry',exact:true}).click()
  await page.locator('.msg-outgoing').filter({hasText:'Hello Casey'}).waitFor()
  const sent=await page.evaluate(()=>window.sent)
  assert(sent.length===2&&sent[0].id===sent[1].id&&sent[1].threadId.includes('33333333'),'retry targets chosen member with same message ID')
  assert(await page.getByPlaceholder('Write a message…').inputValue()==='','confirmed send clears only its draft')
  await back();await select('Alex Example')
  assert(await page.getByPlaceholder('Write a message…').inputValue()==='Draft for Alex','other recipient draft survives send')
  await page.getByRole('button',{name:'New message'}).click()
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'recipient list fits '+width)
  if(shots&&width===390)await page.screenshot({path:resolve(shots,`${social?'social':'business'}-${theme}-picker.png`),fullPage:true})
  assert(errors.length===0,'no browser errors: '+errors.join(';'))
  console.log(`PASS ${social?'Social':'Business'} ${theme} ${width}px`)
  await context.close()
 }
 const page=await browser.newPage({viewport:{width:390,height:844}})
 await page.goto(url+'/?empty=1')
 await page.getByRole('button',{name:'New message'}).click()
 await page.evaluate(()=>window.setDirectoryStatus('loading'))
 await page.getByRole('status').filter({hasText:'Loading members'}).waitFor()
 await page.evaluate(()=>window.setDirectoryStatus('error'))
 await page.getByRole('status').filter({hasText:'Members could not be loaded'}).waitFor()
 await page.evaluate(()=>window.setDirectoryStatus('ready'))
 await page.getByRole('button',{name:'Message Casey Example'}).click()
 await page.getByPlaceholder('Write a message…').fill('Pending for Casey')
 await page.evaluate(()=>window.deferSend=true)
 await page.getByRole('button',{name:'Send message',exact:true}).click()
 await page.getByRole('button',{name:'New message'}).click()
 await page.getByRole('button',{name:'Message Alex Example'}).click()
 await page.getByPlaceholder('Write a message…').fill('Keep for Alex')
 await page.evaluate(()=>window.finishSend())
 await page.waitForFunction(()=>!document.querySelector('[aria-label="Send message"]').disabled)
 assert(await page.getByPlaceholder('Write a message…').inputValue()==='Keep for Alex','late send cannot change recipient or clear their draft')
 assert((await page.locator('header').innerText()).includes('Alex Example'),'late canonical thread ID cannot hijack selection')
 console.log('Mobile recipient and existing conversation workflows passed. No real messages sent.')
} finally {await browser.close();await server.close()}
